# 여러 CSV의 처음 400개 포인트를 파일별/신호별로 독립적으로 0점 보정합니다.
import io
import re
import tempfile
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# ===================== 사용자 설정 =====================
BASELINE_START_IDX = 0   # 시작 데이터 인덱스: 포함
BASELINE_END_IDX = 400   # 종료 데이터 인덱스: 미포함
# 처음 400개 데이터(인덱스 0~399)를 기준으로 사용합니다. CSV 제목 행은 제외합니다.

TIME_COLUMN = "time(s)"
STRESS_COLUMN = "Stress(MPa)"
STRAIN_COLUMN = "Strain Gauge"
# CSV 첫 줄에 열 이름이 있어야 합니다. 이름이 다르면 위 설정을 바꾸세요.
# =======================================================


def read_uploaded_csv(raw_bytes):
    """UTF-8/BOM 또는 CP949 CSV를 읽고 구분자를 자동 인식합니다."""
    for encoding in ("utf-8-sig", "cp949"):
        try:
            text = raw_bytes.decode(encoding)
        except UnicodeDecodeError:
            continue
        return pd.read_csv(io.StringIO(text), sep=None, engine="python")
    raise ValueError("파일을 UTF-8 또는 CP949 형식의 CSV로 저장해 주세요.")


def find_column(df, requested):
    # ' Stress (MPa) '와 'Stress(MPa)'처럼 공백/대소문자가 달라도 인식
    def normalize(value):
        return re.sub(r"\s+", "", str(value)).casefold()

    matches = [c for c in df.columns if normalize(c) == normalize(requested)]
    if len(matches) != 1:
        raise ValueError(
            f"'{requested}' 열을 하나로 식별할 수 없습니다. "
            f"현재 열: {list(df.columns)}. 코드 상단의 열 이름을 확인하세요."
        )
    return matches[0]


def zero_center(df, start_idx, end_idx):
    if (not isinstance(start_idx, (int, np.integer))
            or not isinstance(end_idx, (int, np.integer))
            or start_idx < 0 or end_idx <= start_idx):
        raise ValueError("기준 인덱스는 정수이며 0 <= 시작 < 종료여야 합니다.")
    if end_idx > len(df):
        raise ValueError(
            f"데이터가 {len(df)}개여서 인덱스 {end_idx - 1}까지 선택할 수 없습니다. "
            f"데이터가 {end_idx}개 이상인 파일을 사용하거나 BASELINE_END_IDX를 줄이세요."
        )

    time_col = find_column(df, TIME_COLUMN)
    channels = [find_column(df, STRESS_COLUMN), find_column(df, STRAIN_COLUMN)]
    if len(set([time_col] + channels)) != 3:
        raise ValueError("시간, 응력, 변형률 열을 서로 다르게 지정하세요.")

    time = pd.to_numeric(df[time_col], errors="raise").to_numpy(dtype=float)
    if not np.isfinite(time).all():
        raise ValueError("시간 열에 빈칸/무한대가 있습니다. 시간 데이터를 확인하세요.")
    if np.any(np.diff(time) < 0):
        raise ValueError("시간이 감소하는 행이 있습니다. 시간 순서를 확인하세요.")

    # 행 위치로 선택: 처음 400개 = 인덱스 0~399. 시간값은 그대로 유지합니다.
    mask = np.zeros(len(df), dtype=bool)
    mask[start_idx:end_idx] = True
    if mask.sum() < 2:
        raise ValueError("기준 구간에 최소 2개 데이터 포인트를 지정하세요.")

    result = df.copy()  # 원본 열/행 순서를 유지하고 보정 열만 추가
    details = []
    for column in channels:
        values = pd.to_numeric(df[column], errors="raise").to_numpy(dtype=float)
        if np.isinf(values).any():
            raise ValueError(f"'{column}' 열에 무한대가 있습니다.")
        valid_baseline = values[mask & np.isfinite(values)]
        if len(valid_baseline) < 2:
            raise ValueError(f"'{column}' 기준 구간에 유효한 값이 2개 미만입니다.")

        baseline_mean = np.mean(valid_baseline)
        corrected = values - baseline_mean  # 전체 포인트에서 해당 열의 평균 차감
        output_column = f"{column}_zero"
        if output_column in result.columns:
            raise ValueError(f"'{output_column}' 열이 이미 있습니다. 원본 CSV를 사용하세요.")
        result[output_column] = corrected
        details.append((column, values, corrected, baseline_mean))
    return result, time, mask, details


def plot_result(time, mask, details, file_number):
    fig, axes = plt.subplots(2, 1, figsize=(13, 8), sharex=True)
    labels = ["Stress (MPa)", "Strain Gauge"]
    for ax, ylabel, (_, raw, corrected, mean) in zip(axes, labels, details):
        ax.plot(time, raw, color="salmon", alpha=0.7, label="Raw")
        ax.plot(time, corrected, color="royalblue", linewidth=1.4,
                label="Zero-centered")
        # 선택한 첫 포인트부터 마지막 포인트의 시간까지 빨간색으로 표시
        ax.axvspan(time[mask][0], time[mask][-1], color="red", alpha=0.13,
                   label=f"Baseline interval ({mask.sum()} points)")
        ax.axhline(mean, color="red", linestyle="--", linewidth=1,
                   label=f"Baseline mean = {mean:.6g}")
        ax.axhline(0, color="black", linestyle=":", linewidth=1)
        ax.set_ylabel(ylabel)
        ax.grid(True, linestyle="--", alpha=0.35)
        ax.legend(loc="best")
    axes[-1].set_xlabel("Time (s)")
    fig.suptitle(f"File {file_number}: before / after zero correction")
    fig.tight_layout()
    return fig


def main():
    from google.colab import files
    from IPython.display import display

    print("CSV 여러 개를 한 번에 선택하세요. Ctrl 또는 Shift 키로 다중 선택할 수 있습니다.")
    uploaded = files.upload()
    if not uploaded:
        print("선택된 파일이 없습니다.")
        return

    output_dir = Path(tempfile.mkdtemp(prefix="zero_center_"))
    outputs = []
    summaries = []
    batch_status = []
    total_files = len(uploaded)
    print(f"\n총 {total_files}개 파일을 각각 독립적으로 처리합니다.")

    for number, (filename, content) in enumerate(uploaded.items(), start=1):
        print(f"\n[{number}/{total_files}] {filename}")
        fig = None
        status = {"file": filename, "status": "error", "message": ""}
        try:
            if Path(filename).suffix.lower() != ".csv":
                raise ValueError("CSV 파일만 선택해 주세요.")
            # 매번 현재 파일을 새로 읽고 두 신호의 평균을 각각 다시 계산합니다.
            df = read_uploaded_csv(content)
            result, time, mask, details = zero_center(
                df, BASELINE_START_IDX, BASELINE_END_IDX
            )
            print(f"  기준: 인덱스 {BASELINE_START_IDX}~{BASELINE_END_IDX - 1} "
                  f"({mask.sum()}개), 시간 {time[mask][0]:.8g}~{time[mask][-1]:.8g} s")
            rows = []
            for column, raw, corrected, mean in details:
                print(f"  {column}: 빼준 평균 = {mean:.8g}")
                print(f"  보정 후 기준 구간 평균 = {np.nanmean(corrected[mask]):.3e}")
                if np.isnan(raw).any():
                    print(f"  빈값 {np.isnan(raw).sum()}개: 평균에서 제외하고 빈값 유지")
                rows.append({
                    "file": filename, "channel": column,
                    "baseline_start_idx": BASELINE_START_IDX,
                    "baseline_end_idx_exclusive": BASELINE_END_IDX,
                    "baseline_selected_points": int(mask.sum()),
                    "baseline_first_time_s": time[mask][0],
                    "baseline_last_time_s": time[mask][-1],
                    "baseline_valid_points": int(np.isfinite(raw[mask]).sum()),
                    "subtracted_mean": mean,
                    "corrected_baseline_mean": float(np.nanmean(corrected[mask])),
                })

            stem = f"{number:02d}_{Path(filename).stem}"
            csv_path = output_dir / f"{stem}_zero_corrected.csv"
            png_path = output_dir / f"{stem}_comparison.png"
            result.to_csv(csv_path, index=False, encoding="utf-8-sig")
            fig = plot_result(time, mask, details, number)
            fig.savefig(png_path, dpi=180, bbox_inches="tight")
            plt.show()
            display(result.head())
            outputs.extend([csv_path, png_path])
            summaries.extend(rows)
            status["status"] = "success"
            status["message"] = "두 신호 보정 및 CSV/PNG 저장 완료"
            print("  완료: Stress와 Strain Gauge를 각각 0점 보정했습니다.")
        except Exception as error:
            status["message"] = str(error)
            print(f"  처리하지 못했습니다: {error}")
        finally:
            if fig is not None:
                plt.close(fig)
            batch_status.append(status)

    status_df = pd.DataFrame(batch_status)
    success_count = int((status_df["status"] == "success").sum())
    print(f"\n처리 완료: 전체 {total_files}개 / 성공 {success_count}개 "
          f"/ 실패 {total_files - success_count}개")
    display(status_df)

    # 한 파일에서 오류가 나도 나머지 파일을 계속 처리하고, 오류 사유를 함께 저장합니다.
    status_path = output_dir / "processing_status.csv"
    status_df.to_csv(status_path, index=False, encoding="utf-8-sig")
    outputs.append(status_path)

    if summaries:
        summary_path = output_dir / "baseline_summary.csv"
        summary_df = pd.DataFrame(summaries)
        summary_df.to_csv(summary_path, index=False, encoding="utf-8-sig")
        print("\n파일별/신호별 평균값:")
        display(summary_df[["file", "channel", "subtracted_mean", "corrected_baseline_mean"]])
        outputs.append(summary_path)

    zip_path = output_dir / "zero_correction_results.zip"
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in outputs:
            archive.write(path, arcname=path.name)
    if success_count:
        print("\n보정 CSV, 비교 그래프 PNG, 기준 평균 요약을 ZIP으로 다운로드합니다.")
    else:
        print("\n보정에 성공한 파일이 없습니다. 오류 내역을 ZIP으로 다운로드합니다.")
    files.download(str(zip_path))


if __name__ == "__main__":
    main()

